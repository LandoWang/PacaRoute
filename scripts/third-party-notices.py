#!/usr/bin/env python3
"""Collect dependency license texts for the shipped Go binary and React bundle."""
import json
import pathlib
import shutil
import subprocess

root = pathlib.Path(__file__).resolve().parents[1]
output = ['# Third-party notices\n\nGenerated by `scripts/third-party-notices.py`. Dependency license texts follow.\n']
missing = []
def add(name, directory):
    files = sorted(p for p in directory.iterdir() if p.is_file() and (p.name.lower().split('.')[0] in ('license', 'licence', 'copying', 'notice') or p.name.lower().startswith(('license-', 'license_'))))
    # This package omits LICENSE from its npm files list. Vendor the upstream
    # text from https://github.com/theKashey/react-remove-scroll-bar/blob/master/LICENSE.
    if not files and name.startswith('react-remove-scroll-bar '):
        files = [root / 'scripts/licenses/react-remove-scroll-bar.txt']
    if not files:
        missing.append(name)
        return
    output.append('\n## ' + name + '\n')
    for p in files:
        output.append('\n### ' + p.name + '\n\n```text\n' + p.read_text(errors='replace').strip() + '\n```\n')

go = shutil.which('go') or '/opt/homebrew/bin/go'
raw = subprocess.check_output([go, 'list', '-m', '-json', 'all'], cwd=root, text=True)
decoder = json.JSONDecoder()
while raw.strip():
    item, end = decoder.raw_decode(raw.lstrip())
    raw = raw.lstrip()[end:]
    if not item.get('Main') and item.get('Dir'):
        add(item['Path'] + ' ' + item['Version'], pathlib.Path(item['Dir']))
lock = json.loads((root / 'apps/web/package-lock.json').read_text())
for path, item in sorted(lock['packages'].items()):
    if path and not item.get('dev'):
        add(path.removeprefix('node_modules/') + ' ' + item['version'], root / 'apps/web' / path)
if missing:
    raise SystemExit('Missing license files: ' + ', '.join(missing))
output.append('\n## Provider and product icons\n\n' + (root / 'apps/web/src/assets/brands/README.md').read_text() + '\n' + (root / 'scripts/licenses/brand-icons-cc0.md').read_text())
output.append('\n### Lobe Icons\n\n```text\n' + (root / 'scripts/licenses/lobe-icons.txt').read_text().strip() + '\n```\n')
(root / 'THIRD_PARTY_NOTICES.md').write_text(''.join(output))
print('Updated third-party notices')
